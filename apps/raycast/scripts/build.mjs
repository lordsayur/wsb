// Builds the Raycast extension. specs/raycast/spec.md — Supabase is the only
// runtime source, so its public config is baked into the bundle from the
// environment before `ray build` runs. No remote code, no analytics.
import { mkdir, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const configOnly = process.argv.includes('--config-only')
const dev = process.argv.includes('--dev')

const url = process.env.WSB_SUPABASE_URL ?? ''
const anonKey =
  process.env.WSB_SUPABASE_ANON_KEY ??
  process.env.NUXT_PUBLIC_SUPABASE_ANON_KEY ??
  ''

const generated = join(root, 'src/shared/config.generated.ts')
await mkdir(dirname(generated), { recursive: true })
await writeFile(
  generated,
  [
    '// Generated by scripts/build.mjs; do not edit. specs/raycast/spec.md.',
    `export const SUPABASE_URL = ${JSON.stringify(url)}`,
    `export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)}`,
    '',
  ].join('\n'),
)

if (configOnly) process.exit(0)

// Keep the artifact inside the repo (dist/) instead of Raycast's global
// extensions directory, so CI builds it the same way other shells do.
execFileSync(
  'ray',
  ['build', '-e', dev ? 'dev' : 'dist', '-o', 'dist', '--exit-on-error'],
  { cwd: root, stdio: 'inherit' },
)
